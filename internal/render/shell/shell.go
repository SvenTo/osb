// Package shell renders steps as a readable POSIX shell script.
package shell

import (
	"embed"
	"encoding/base64"
	"fmt"
	"strings"
	"unicode/utf8"

	"github.com/SvenTo/osb/internal/expr"
	"github.com/SvenTo/osb/internal/flavor"
	"github.com/SvenTo/osb/internal/ops"
)

//go:embed lib/*.sh
var libFS embed.FS

// Library returns the helper library for a flavor.
func Library(fl *flavor.Flavor) string {
	common, _ := libFS.ReadFile("lib/common.sh")
	pkg := "lib/apt.sh"
	if fl.IsArch() {
		pkg = "lib/pacman.sh"
	}
	pm, _ := libFS.ReadFile(pkg)
	lib := string(common) + string(pm)
	if opts, ok := fl.Vars["apt-options"].(string); ok && opts != "" && fl.IsDebian() {
		lib = strings.Replace(lib, "OSB_APT_OPTIONS=${OSB_APT_OPTIONS:-}", "OSB_APT_OPTIONS=${OSB_APT_OPTIONS:-"+opts+"}", 1)
	}
	return lib
}

// Doc is the input of the shell renderer.
type Doc struct {
	Name    string
	Source  string
	Flavor  *flavor.Flavor
	Target  string
	Command string
	Version string
	Steps   []*ops.Step
	// Total is the number of steps of the whole plan (default: len(Steps)).
	Total int
	// Notes are added as comments before the steps.
	Notes []string
}

// Q quotes a word for the shell.
func Q(s string) string { return expr.ShellQuote(s) }

// Render renders a complete self-contained script.
func Render(d *Doc) string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	fmt.Fprintf(&b, "# Generated by osb %s - do not edit, regenerate instead.\n", d.Version)
	if d.Name != "" {
		fmt.Fprintf(&b, "# Config:  %s (%s)\n", d.Name, d.Source)
	} else {
		fmt.Fprintf(&b, "# Config:  %s\n", d.Source)
	}
	fmt.Fprintf(&b, "# Flavor:  %s\n", d.Flavor.Name)
	fmt.Fprintf(&b, "# Target:  %s\n", d.Target)
	if d.Command != "" {
		fmt.Fprintf(&b, "# Command: %s\n", d.Command)
	}
	b.WriteString("set -eu\n\n")
	b.WriteString(Library(d.Flavor))
	b.WriteString("\n# --- configuration -----------------------------------------------------------\n")
	b.WriteString("require_root\n")
	fmt.Fprintf(&b, "check_flavor %s\n", strings.Join(quoteAll(d.Flavor.OSReleaseIDs), " "))
	total := d.Total
	if total == 0 {
		total = len(d.Steps)
	}
	fmt.Fprintf(&b, "OSB_STEPS=%d\n", total)
	if len(d.Notes) > 0 {
		b.WriteString("\n")
		for _, n := range d.Notes {
			b.WriteString("# " + n + "\n")
		}
	}
	for _, s := range d.Steps {
		b.WriteString("\n")
		if d.Total > 0 {
			fmt.Fprintf(&b, "OSB_STEP=%d\n", s.Index-1)
		}
		b.WriteString(StepScript(s, d.Flavor, total))
	}
	b.WriteString("\nosb_finish\n")
	return b.String()
}

func quoteAll(l []string) []string {
	out := make([]string, len(l))
	for i, s := range l {
		out[i] = Q(s)
	}
	return out
}

// StepHeader returns the comment block introducing a step.
func StepHeader(s *ops.Step, total int) string {
	var b strings.Builder
	b.WriteString("# " + strings.Repeat("-", 77) + "\n")
	fmt.Fprintf(&b, "# Step %d/%d: %s\n", s.Index, total, oneLine(s.Title))
	var meta []string
	if s.Name != "" {
		meta = append(meta, "name: "+s.Name)
	}
	if s.Action != "" {
		meta = append(meta, "action: "+s.Action)
	}
	if s.Source != "" {
		meta = append(meta, s.Source)
	}
	if len(meta) > 0 {
		fmt.Fprintf(&b, "# (%s)\n", strings.Join(meta, ", "))
	}
	b.WriteString("# " + strings.Repeat("-", 77) + "\n")
	return b.String()
}

func oneLine(s string) string {
	return strings.ReplaceAll(strings.TrimSpace(s), "\n", " ")
}

// StepScript renders a step including header, guards and error handling.
func StepScript(s *ops.Step, fl *flavor.Flavor, total int) string {
	var b strings.Builder
	b.WriteString(StepHeader(s, total))
	fmt.Fprintf(&b, "step %s\n", Q(oneLine(s.Title)))
	b.WriteString(Guarded(s, Body(s, fl)))
	return b.String()
}

// Guarded wraps a step body with run-time guards and error handling.
func Guarded(s *ops.Step, body string) string {
	if s.OnError == "continue" {
		body = "set +e\n(\nset -e\n" + body + ")\nosb_rc=$?\nset -e\n" +
			"if [ \"$osb_rc\" -ne 0 ]; then\n  OSB_FAILED=$((OSB_FAILED + 1))\n  warn \"step failed with exit code $osb_rc, continuing\"\nfi\n"
	}
	cond := GuardCondition(s.Guards)
	if cond == "" {
		return body
	}
	return "if " + cond + "; then\n" + body + "else\n  log " + Q("skipped: "+GuardDescription(s.Guards)) + "\nfi\n"
}

// GuardCondition returns a shell condition for guards, or "".
func GuardCondition(guards []ops.Guard) string {
	var parts []string
	for _, g := range guards {
		switch g.Kind {
		case "only-if":
			parts = append(parts, "( "+g.Value+" ) >/dev/null 2>&1")
		case "unless":
			parts = append(parts, "! ( "+g.Value+" ) >/dev/null 2>&1")
		case "creates":
			parts = append(parts, "[ ! -e "+Q(g.Value)+" ]")
		}
	}
	return strings.Join(parts, " && ")
}

// GuardDescription describes the guards for log output.
func GuardDescription(guards []ops.Guard) string {
	var parts []string
	for _, g := range guards {
		switch g.Kind {
		case "only-if":
			parts = append(parts, "only if "+g.Value)
		case "unless":
			parts = append(parts, "unless "+g.Value)
		case "creates":
			parts = append(parts, g.Value+" exists")
		}
	}
	return strings.Join(parts, ", ")
}

// Body renders the ops of a step without guards.
func Body(s *ops.Step, fl *flavor.Flavor) string {
	var b strings.Builder
	for _, o := range s.Ops {
		b.WriteString(Op(o, fl))
	}
	return b.String()
}

// Op renders a single op as shell code ending with a newline.
func Op(o ops.Op, fl *flavor.Flavor) string {
	switch t := o.(type) {
	case ops.File:
		return File(t)
	case ops.Shell:
		s := t.Script
		if s != "" && !strings.HasSuffix(s, "\n") {
			s += "\n"
		}
		return s
	case ops.Packages:
		if len(t.Names) == 0 {
			return ""
		}
		fn := "pkg_install"
		if t.Missing {
			fn = "pkg_ensure"
		}
		return fn + " " + strings.Join(quoteAll(t.Names), " ") + "\n"
	case ops.User:
		return User(t)
	case ops.Hostname:
		return Hostname(t, fl)
	case ops.Env:
		var b strings.Builder
		for _, kv := range t.Vars {
			fmt.Fprintf(&b, "set_env_var /etc/environment %s %s\n", Q(kv.Key), Q(kv.Value))
		}
		return b.String()
	case ops.Download:
		return "download " + joinArgs(t.URL, t.Path, t.SHA256, t.Mode, t.Owner, t.Group) + "\n"
	case ops.Note:
		if t.Warn {
			return "warn " + Q(t.Message) + "\n"
		}
		return "log " + Q(t.Message) + "\n"
	}
	return fmt.Sprintf("# unsupported op %T\n", o)
}

// joinArgs quotes arguments and drops trailing empty ones.
func joinArgs(args ...string) string {
	for len(args) > 0 && args[len(args)-1] == "" {
		args = args[:len(args)-1]
	}
	return strings.Join(quoteAll(args), " ")
}

// IsText reports whether content can be embedded in a heredoc.
func IsText(c []byte) bool {
	if !utf8.Valid(c) {
		return false
	}
	for _, r := range string(c) {
		if r == 0 || (r < 32 && r != '\n' && r != '\t' && r != '\r') {
			return false
		}
	}
	return true
}

// Delimiter returns a heredoc delimiter that does not occur in content.
func Delimiter(content string, base string) string {
	d := base
	for i := 1; ; i++ {
		if !containsLine(content, d) {
			return d
		}
		d = fmt.Sprintf("%s_%d", base, i)
	}
}

func containsLine(content, line string) bool {
	for _, l := range strings.Split(content, "\n") {
		if strings.TrimRight(l, "\r") == line {
			return true
		}
	}
	return false
}

// Heredoc returns "<<'DELIM'\ncontent\nDELIM\n" for content ending in a newline.
func Heredoc(content string) string {
	d := Delimiter(content, "OSB_EOF")
	return "<<'" + d + "'\n" + content + d + "\n"
}

// File renders a file op.
func File(f ops.File) string {
	mode := f.Mode
	if mode == "" {
		mode = "0644"
	}
	c := string(f.Content)
	if f.Append {
		if !strings.HasSuffix(c, "\n") {
			c += "\n"
		}
		return "append_file " + Q(f.Path) + " " + Heredoc(c)
	}
	args := joinArgs(f.Path, mode, f.Owner, f.Group)
	switch {
	case !IsText(f.Content):
		return "write_file_b64 " + args + " " + Heredoc(wrap(base64.StdEncoding.EncodeToString(f.Content), 76))
	case c == "":
		return "write_file " + args + " < /dev/null\n"
	case strings.HasSuffix(c, "\n"):
		return "write_file " + args + " " + Heredoc(c)
	case !strings.Contains(c, "\n"):
		return "printf '%s' " + Q(c) + " | write_file " + args + "\n"
	default:
		return "printf '%s' " + Q(c) + " |\n  write_file " + args + "\n"
	}
}

func wrap(s string, n int) string {
	var b strings.Builder
	for len(s) > n {
		b.WriteString(s[:n] + "\n")
		s = s[n:]
	}
	if s != "" {
		b.WriteString(s + "\n")
	}
	return b.String()
}

// User renders a user op.
func User(u ops.User) string {
	var b strings.Builder
	for _, g := range u.Groups {
		fmt.Fprintf(&b, "getent group %s >/dev/null || groupadd %s\n", Q(g), Q(g))
	}
	args := []string{"useradd"}
	if u.System {
		args = append(args, "--system")
	}
	if u.CreateHome {
		args = append(args, "--create-home")
	} else {
		args = append(args, "--no-create-home")
	}
	if u.UID != "" {
		args = append(args, "--uid", Q(u.UID))
	}
	if u.Home != "" {
		args = append(args, "--home-dir", Q(u.Home))
	}
	if u.Shell != "" {
		args = append(args, "--shell", Q(u.Shell))
	}
	if u.Comment != "" {
		args = append(args, "--comment", Q(u.Comment))
	}
	args = append(args, Q(u.Name))
	fmt.Fprintf(&b, "id -u %s >/dev/null 2>&1 || %s\n", Q(u.Name), strings.Join(args, " "))
	if len(u.Groups) > 0 {
		fmt.Fprintf(&b, "usermod -aG %s %s\n", Q(strings.Join(u.Groups, ",")), Q(u.Name))
	}
	return b.String()
}

// Hostname renders a hostname op.
func Hostname(h ops.Hostname, fl *flavor.Flavor) string {
	n := Q(h.Name)
	return fmt.Sprintf("printf '%%s\\n' %s | write_file /etc/hostname 0644\n", n) +
		fmt.Sprintf("ensure_line /etc/hosts %s '^127\\.0\\.1\\.1[[:space:]]'\n", Q("127.0.1.1 "+h.Name)) +
		fmt.Sprintf("if systemd_available && has_cmd hostnamectl; then hostnamectl set-hostname %s; else hostname %s 2>/dev/null || true; fi\n", n, n)
}
