// Package dockerfile renders a plan as a Dockerfile and build context.
package dockerfile

import (
	"encoding/json"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/SvenTo/osb/internal/config"
	"github.com/SvenTo/osb/internal/engine"
	"github.com/SvenTo/osb/internal/expr"
	"github.com/SvenTo/osb/internal/ops"
	"github.com/SvenTo/osb/internal/render/shell"
)

// Result describes a rendered build context.
type Result struct {
	// Dir is the build context; the Dockerfile is Dir/Dockerfile.
	Dir string
	// Secrets maps BuildKit secret ids to files (outside the context).
	Secrets map[string]string
	// BuildArgs are the extra arguments needed for docker build.
	BuildArgs []string
}

// Options configures rendering.
type Options struct {
	Version string
	Command string
	// ExtraSteps are appended after the plan's steps (e.g. wsl.conf).
	ExtraSteps []*ops.Step
}

type renderer struct {
	plan    *engine.Plan
	dir     string
	b       strings.Builder
	nfile   int
	secrets map[string]string
	total   int
}

// Render writes Dockerfile, .dockerignore, the helper library and files into dir.
func Render(plan *engine.Plan, dir string, opts Options) (*Result, error) {
	if err := os.MkdirAll(filepath.Join(dir, ".osb"), 0o755); err != nil {
		return nil, err
	}
	for _, sub := range []string{"files", "secrets"} {
		_ = os.RemoveAll(filepath.Join(dir, sub))
	}
	r := &renderer{plan: plan, dir: dir, secrets: map[string]string{}}
	settings := plan.Artifact("dockerfile")
	steps := append(append([]*ops.Step{}, plan.Steps...), opts.ExtraSteps...)
	r.total = len(steps)

	base := expr.Stringify(settings["base-image"])
	if base == "" {
		base = plan.Flavor.BaseImage
	}
	r.line("# syntax=docker/dockerfile:1")
	r.line("# Generated by osb %s - do not edit, regenerate instead.", opts.Version)
	r.line("# Config:  %s", config.DisplayPath(plan.Config.File))
	r.line("# Flavor:  %s", plan.Flavor.Name)
	if opts.Command != "" {
		r.line("# Command: %s", opts.Command)
	}
	r.line("FROM %s", base)
	labels := map[string]string{}
	if plan.Config.Name != "" {
		labels["org.opencontainers.image.title"] = plan.Config.Name
	}
	if plan.Config.Description != "" {
		labels["org.opencontainers.image.description"] = plan.Config.Description
	}
	if m, ok := settings["labels"].(map[string]any); ok {
		for k, v := range m {
			labels[k] = expr.Stringify(v)
		}
	}
	if len(labels) > 0 {
		keys := sortedKeys(labels)
		var parts []string
		for _, k := range keys {
			parts = append(parts, quoteWord(k)+"="+quote(labels[k]))
		}
		r.line("LABEL %s", strings.Join(parts, " \\\n      "))
	}
	if m, ok := settings["env"].(map[string]any); ok && len(m) > 0 {
		r.env(m)
	}

	for _, s := range steps {
		if err := r.step(s); err != nil {
			return nil, err
		}
	}

	r.b.WriteString("\n")
	if vols := list(settings["volumes"]); len(vols) > 0 {
		r.line("VOLUME %s", jsonArray(vols))
	}
	if ports := list(settings["expose"]); len(ports) > 0 {
		r.line("EXPOSE %s", strings.Join(ports, " "))
	}
	if wd := expr.Stringify(settings["workdir"]); wd != "" {
		r.line("WORKDIR %s", wd)
	}
	if u := expr.Stringify(settings["user"]); u != "" {
		r.line("USER %s", u)
	}
	if ep, ok := settings["entrypoint"]; ok && ep != nil {
		r.line("ENTRYPOINT %s", execForm(ep))
	}
	if cmd, ok := settings["cmd"]; ok && cmd != nil {
		r.line("CMD %s", execForm(cmd))
	}

	if err := os.WriteFile(filepath.Join(dir, "Dockerfile"), []byte(r.b.String()), 0o644); err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(dir, ".osb", "lib.sh"), []byte(shell.Library(plan.Flavor)), 0o644); err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(dir, ".dockerignore"), []byte("# osb: secrets are passed as BuildKit secrets, never as context\nsecrets/\n"), 0o644); err != nil {
		return nil, err
	}
	res := &Result{Dir: dir, Secrets: r.secrets}
	ids := sortedKeys(r.secrets)
	for _, id := range ids {
		res.BuildArgs = append(res.BuildArgs, "--secret", "id="+id+",src="+r.secrets[id])
	}
	return res, nil
}

func (r *renderer) line(format string, a ...any) {
	fmt.Fprintf(&r.b, format+"\n", a...)
}

func (r *renderer) env(m map[string]any) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var parts []string
	for _, k := range keys {
		parts = append(parts, k+"="+quote(expr.Stringify(m[k])))
	}
	r.line("ENV %s", strings.Join(parts, " \\\n    "))
}

func (r *renderer) header(s *ops.Step) {
	r.b.WriteString("\n")
	for _, l := range strings.Split(strings.TrimRight(shell.StepHeader(s, r.total), "\n"), "\n") {
		r.b.WriteString(l + "\n")
	}
}

func (r *renderer) stepPrelude(s *ops.Step) string {
	return fmt.Sprintf("OSB_STEP=%d OSB_STEPS=%d\nstep %s\n", s.Index-1, r.total, shell.Q(strings.ReplaceAll(s.Title, "\n", " ")))
}

func (r *renderer) step(s *ops.Step) error {
	r.header(s)
	if len(s.Ops) == 0 {
		r.line("# (nothing to do)")
		return nil
	}
	if len(s.Guards) > 0 || s.OnError == "continue" || s.Secret {
		body := shell.Guarded(s, shell.Body(s, r.plan.Flavor))
		return r.run(s, r.stepPrelude(s)+body+cleanIfPackages(s.Ops), s.Secret)
	}
	var pending strings.Builder
	announced := false
	flush := func() error {
		if pending.Len() == 0 {
			return nil
		}
		script := pending.String()
		if !announced {
			script = r.stepPrelude(s) + script
			announced = true
		}
		pending.Reset()
		return r.run(s, script, false)
	}
	hasPkgs := false
	for _, o := range s.Ops {
		switch t := o.(type) {
		case ops.File:
			if t.Append {
				pending.WriteString(shell.Op(t, r.plan.Flavor))
				continue
			}
			if err := flush(); err != nil {
				return err
			}
			if err := r.copy(t); err != nil {
				return err
			}
		case ops.Download:
			if err := flush(); err != nil {
				return err
			}
			r.add(t)
		case ops.Env:
			if err := flush(); err != nil {
				return err
			}
			m := map[string]any{}
			for _, kv := range t.Vars {
				m[kv.Key] = kv.Value
			}
			r.env(m)
			pending.WriteString(shell.Op(t, r.plan.Flavor))
		case ops.Note:
			if err := flush(); err != nil {
				return err
			}
			r.line("# %s", t.Message)
		case ops.Packages:
			hasPkgs = true
			pending.WriteString(shell.Op(t, r.plan.Flavor))
		default:
			pending.WriteString(shell.Op(t, r.plan.Flavor))
		}
	}
	if hasPkgs && pending.Len() > 0 {
		pending.WriteString("pkg_clean\n")
	}
	return flush()
}

func cleanIfPackages(list []ops.Op) string {
	for _, o := range list {
		if _, ok := o.(ops.Packages); ok {
			return "pkg_clean\n"
		}
	}
	return ""
}

// run emits a RUN instruction with a heredoc script.
func (r *renderer) run(s *ops.Step, script string, secret bool) error {
	full := "set -eu\n. /run/osb/lib.sh\n" + script
	if secret {
		id := fmt.Sprintf("osb-step-%d", s.Index)
		p := filepath.Join(r.dir, "secrets", id+".sh")
		if err := os.MkdirAll(filepath.Dir(p), 0o700); err != nil {
			return err
		}
		if err := os.WriteFile(p, []byte(full), 0o600); err != nil {
			return err
		}
		abs, _ := filepath.Abs(p)
		r.secrets[id] = abs
		r.line("# This step contains secrets; its script is passed as BuildKit secret %q.", id)
		r.line("RUN --mount=type=bind,source=.osb,target=/run/osb --mount=type=secret,id=%s,target=/run/osb-secrets/%s.sh \\\n    sh /run/osb-secrets/%s.sh", id, id, id)
		return nil
	}
	d := shell.Delimiter(full, "OSB_RUN")
	r.line("RUN --mount=type=bind,source=.osb,target=/run/osb <<'%s'\n%s%s", d, full, d)
	return nil
}

func (r *renderer) copy(f ops.File) error {
	r.nfile++
	name := fmt.Sprintf("%03d-%s", r.nfile, path.Base(f.Path))
	p := filepath.Join(r.dir, "files", name)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(p, f.Content, 0o644); err != nil {
		return err
	}
	mode := f.Mode
	if mode == "" {
		mode = "0644"
	}
	flags := "--chmod=" + mode
	if own := owner(f.Owner, f.Group); own != "" {
		flags += " --chown=" + own
	}
	r.line("COPY %s %s %s", flags, quoteWord("files/"+name), quoteWord(f.Path))
	return nil
}

func (r *renderer) add(d ops.Download) {
	flags := []string{}
	if d.SHA256 != "" {
		flags = append(flags, "--checksum=sha256:"+d.SHA256)
	}
	mode := d.Mode
	if mode == "" {
		mode = "0644"
	}
	flags = append(flags, "--chmod="+mode)
	if own := owner(d.Owner, d.Group); own != "" {
		flags = append(flags, "--chown="+own)
	}
	r.line("ADD %s %s %s", strings.Join(flags, " "), quoteWord(d.URL), quoteWord(d.Path))
}

func owner(o, g string) string {
	switch {
	case o != "" && g != "":
		return o + ":" + g
	case o != "":
		return o
	case g != "":
		return "root:" + g
	}
	return ""
}

// quote quotes a value for ENV/LABEL (double quotes, no variable expansion).
func quote(s string) string {
	s = strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, "\n", `\n`).Replace(s)
	return `"` + s + `"`
}

func quoteWord(s string) string {
	if strings.ContainsAny(s, " \t\"'$\\") {
		return quote(s)
	}
	return s
}

func list(v any) []string {
	switch t := v.(type) {
	case []any:
		var out []string
		for _, e := range t {
			out = append(out, expr.Stringify(e))
		}
		return out
	case string:
		if t == "" {
			return nil
		}
		return strings.Fields(t)
	case int64:
		return []string{strconv.FormatInt(t, 10)}
	}
	return nil
}

func jsonArray(l []string) string {
	b, _ := json.Marshal(l)
	return string(b)
}

func execForm(v any) string {
	if s, ok := v.(string); ok {
		return s
	}
	return jsonArray(list(v))
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
