// Package dockerfile renders a plan as a self-contained Dockerfile: plain
// commands, files as heredocs, no build context and no osb helper library.
package dockerfile

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/SvenTo/osb/internal/config"
	"github.com/SvenTo/osb/internal/engine"
	"github.com/SvenTo/osb/internal/expr"
	"github.com/SvenTo/osb/internal/ops"
	"github.com/SvenTo/osb/internal/render/shell"
)

// Result is a rendered Dockerfile.
type Result struct {
	// Dir is the build context directory after Write ("" before).
	Dir string
	// Files are the files of the build context: just the Dockerfile.
	Files []File
	// Secrets are the BuildKit secrets the Dockerfile uses.
	Secrets []Secret
	// BuildArgs are the extra arguments needed for docker build.
	BuildArgs []string
}

// Secret is a value passed with `docker build --secret id=ID,env=Env`.
type Secret struct {
	ID    string
	Env   string
	Value string
}

// File is a file of the rendered build context.
type File struct {
	Path    string // slash separated, relative to the context directory
	Content []byte
	Mode    os.FileMode
}

// Options configures rendering.
type Options struct {
	Version string
	Command string
	// ExtraSteps are appended after the plan's steps (e.g. wsl.conf).
	ExtraSteps []*ops.Step
}

type renderer struct {
	plan    *engine.Plan
	b       strings.Builder
	total   int
	secrets []Secret
	used    map[string]bool
	items   []instr
	pending string // comment of the current step, until its first instruction

	cache    string // package-cache: tmpfs, cache or remove
	merge    bool   // merge-steps
	slim     bool
	upgraded bool // Arch: the base image is upgraded in the first RUN
}

// instr is a Dockerfile instruction of a step, before RUNs are merged.
type instr struct {
	header string   // step comment for the first instruction of a step
	text   string   // a non-RUN instruction; "" for RUN
	script string   // RUN: shell script
	mounts []string // RUN: secret mounts
}

// Render writes the Dockerfile into dir.
func Render(plan *engine.Plan, dir string, opts Options) (*Result, error) {
	res, err := Generate(plan, opts)
	if err != nil {
		return nil, err
	}
	if err := res.Write(dir); err != nil {
		return nil, err
	}
	return res, nil
}

// Write writes the build context into dir.
func (res *Result) Write(dir string) error {
	for _, f := range res.Files {
		p := filepath.Join(dir, filepath.FromSlash(f.Path))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, f.Content, f.Mode); err != nil {
			return err
		}
	}
	// Older osb versions wrote helper files next to the Dockerfile.
	for _, old := range []string{".osb", "files", "secrets", ".dockerignore"} {
		_ = os.RemoveAll(filepath.Join(dir, old))
	}
	res.Dir = dir
	return nil
}

// Environ returns the environment variables that hold the secret values,
// for running docker build.
func (res *Result) Environ() []string {
	var env []string
	for _, s := range res.Secrets {
		env = append(env, s.Env+"="+s.Value)
	}
	return env
}

// Generate renders the Dockerfile in memory.
func Generate(plan *engine.Plan, opts Options) (*Result, error) {
	settings := plan.Artifact("dockerfile")
	r := &renderer{plan: plan, used: map[string]bool{}, cache: "tmpfs", merge: true}
	if v := expr.Stringify(settings["package-cache"]); v != "" {
		r.cache = v
	}
	if r.cache != "tmpfs" && r.cache != "cache" && r.cache != "remove" {
		return nil, fmt.Errorf("artifacts.dockerfile.package-cache: %q is not tmpfs, cache or remove", r.cache)
	}
	if v, ok := settings["merge-steps"]; ok {
		r.merge = isTrue(v)
	}
	r.slim = isTrue(settings["slim"])
	r.secrets = secretsOf(plan)
	steps := append(append([]*ops.Step{}, plan.Steps...), opts.ExtraSteps...)
	r.total = len(steps)

	for _, s := range steps {
		if err := r.step(s); err != nil {
			return nil, err
		}
	}
	r.items = append(r.setup(), r.items...)
	r.writeItems()
	body := r.b.String()
	r.b.Reset()

	base := expr.Stringify(settings["base-image"])
	if base == "" {
		base = plan.Flavor.BaseImage
	}
	name := plan.Config.Name
	if name == "" {
		name = "osb"
	}
	var used []Secret
	for _, s := range r.secrets {
		if r.used[s.ID] {
			used = append(used, s)
		}
	}
	var build []string
	for _, s := range used {
		build = append(build, "--secret", "id="+s.ID+",env="+s.Env)
	}

	r.line("# syntax=docker/dockerfile:1")
	r.line("# %s for %s, generated by osb %s from %s.", name, plan.Flavor.Name, opts.Version, config.DisplayPath(plan.Config.File))
	r.line("# The file is self-contained: build it as it is, edit it, or regenerate it with")
	if opts.Command != "" {
		r.line("#   %s", opts.Command)
	}
	if len(used) > 0 {
		r.line("# Secrets are passed at build time, never stored in the image:")
		r.line("#   %s docker build %s -t %s .", strings.Join(secretEnvs(used), " "), strings.Join(build, " "), name)
	} else {
		r.line("# Build: docker build -t %s .", name)
	}
	r.line("")
	r.line("FROM %s", base)
	labels := map[string]string{}
	if plan.Config.Name != "" {
		labels["org.opencontainers.image.title"] = plan.Config.Name
	}
	if plan.Config.Description != "" {
		labels["org.opencontainers.image.description"] = plan.Config.Description
	}
	if m, ok := settings["labels"].(map[string]any); ok {
		for k, v := range m {
			labels[k] = expr.Stringify(v)
		}
	}
	if len(labels) > 0 {
		var parts []string
		for _, k := range sortedKeys(labels) {
			parts = append(parts, quoteWord(k)+"="+quote(labels[k]))
		}
		r.line("LABEL %s", strings.Join(parts, " \\\n      "))
	}
	if plan.Flavor.IsDebian() {
		r.line("ARG DEBIAN_FRONTEND=noninteractive")
	}
	r.line("SHELL [\"/bin/sh\", \"-eu\", \"-c\"]")
	if m, ok := settings["env"].(map[string]any); ok && len(m) > 0 {
		r.line("%s", envInstr(m))
	}
	r.b.WriteString(body)

	r.b.WriteString("\n")
	if vols := list(settings["volumes"]); len(vols) > 0 {
		r.line("VOLUME %s", jsonArray(vols))
	}
	if ports := list(settings["expose"]); len(ports) > 0 {
		r.line("EXPOSE %s", strings.Join(ports, " "))
	}
	if wd := expr.Stringify(settings["workdir"]); wd != "" {
		r.line("WORKDIR %s", wd)
	}
	if u := expr.Stringify(settings["user"]); u != "" {
		r.line("USER %s", u)
	}
	ep, hasEP := settings["entrypoint"]
	if hasEP && ep != nil {
		r.line("ENTRYPOINT %s", execForm(ep))
	}
	if cmd, ok := settings["cmd"]; ok && cmd != nil {
		r.line("CMD %s", execForm(cmd))
	} else if !hasEP || ep == nil {
		r.line("CMD [\"/bin/bash\"]")
	}

	res := &Result{Files: []File{{Path: "Dockerfile", Content: []byte(r.b.String()), Mode: 0o644}}, Secrets: used, BuildArgs: build}
	return res, nil
}

// secretsOf maps the secret values of the plan to BuildKit secrets, named
// after the top-level secret arguments.
func secretsOf(plan *engine.Plan) []Secret {
	var out []Secret
	seen := map[string]bool{}
	for _, a := range plan.Config.Arguments {
		v, ok := plan.Args[a.Name].(string)
		if a.Type != "secret" || !ok || len(v) < 3 || seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, Secret{ID: a.Name, Env: engine.EnvName(a.Name), Value: v})
	}
	for i, v := range plan.Secrets.Values() {
		if !seen[v] {
			seen[v] = true
			id := fmt.Sprintf("osb-secret-%d", i+1)
			out = append(out, Secret{ID: id, Env: "OSB_SECRET_" + strconv.Itoa(i+1), Value: v})
		}
	}
	// Longest values first, so that a secret containing another one wins.
	sort.SliceStable(out, func(i, j int) bool { return len(out[i].Value) > len(out[j].Value) })
	return out
}

func secretEnvs(list []Secret) []string {
	var out []string
	for _, s := range list {
		out = append(out, s.Env+"=...")
	}
	return out
}

func (r *renderer) line(format string, a ...any) {
	fmt.Fprintf(&r.b, format+"\n", a...)
}

func envInstr(m map[string]any) string {
	var parts []string
	for _, k := range sortedKeys(m) {
		parts = append(parts, k+"="+quote(expr.Stringify(m[k])))
	}
	return "ENV " + strings.Join(parts, " \\\n    ")
}

func (r *renderer) header(s *ops.Step) {
	title := strings.ReplaceAll(s.Title, "\n", " ")
	if s.Action != "" && !strings.HasSuffix(title, s.Action) {
		title += " (" + s.Action + ")"
	}
	r.pending = fmt.Sprintf("# %d/%d %s", s.Index, r.total, r.plan.Secrets.String(title))
}

// emit adds an instruction to the current step.
func (r *renderer) emit(in instr) {
	in.header, r.pending = r.pending, ""
	r.items = append(r.items, in)
}

func (r *renderer) text(format string, a ...any) {
	r.emit(instr{text: fmt.Sprintf(format, a...)})
}

func (r *renderer) step(s *ops.Step) error {
	r.header(s)
	if len(s.Ops) == 0 {
		r.text("# (nothing to do)")
		return nil
	}
	fl := r.plan.Flavor
	// Guards, error handling and secrets need the whole step in one script.
	if len(s.Guards) > 0 || s.OnError == "continue" || s.Secret {
		var body strings.Builder
		for _, o := range s.Ops {
			body.WriteString(r.opScript(o))
		}
		return r.run(shell.Guarded(s, body.String()), s.Secret)
	}
	var pending strings.Builder
	flush := func() error {
		if pending.Len() == 0 {
			return nil
		}
		script := pending.String()
		pending.Reset()
		return r.run(script, false)
	}
	for _, o := range s.Ops {
		switch t := o.(type) {
		case ops.File:
			if t.Append || !shell.IsText(t.Content) {
				pending.WriteString(shell.Op(t, fl))
				continue
			}
			if err := flush(); err != nil {
				return err
			}
			r.copy(t)
		case ops.Download:
			if err := flush(); err != nil {
				return err
			}
			r.addURL(t)
		case ops.Env:
			if err := flush(); err != nil {
				return err
			}
			m := map[string]any{}
			for _, kv := range t.Vars {
				m[kv.Key] = kv.Value
			}
			r.text("%s", envInstr(m))
		case ops.Note:
			if err := flush(); err != nil {
				return err
			}
			r.text("# %s", t.Message)
		default:
			pending.WriteString(r.opScript(o))
		}
	}
	return flush()
}

// opScript renders an op as shell code; packages become plain commands.
func (r *renderer) opScript(o ops.Op) string {
	switch t := o.(type) {
	case ops.Packages:
		if len(t.Names) == 0 {
			return ""
		}
		return r.packagesCommand(t.Names)
	case ops.Env:
		var b strings.Builder
		for _, kv := range t.Vars {
			fmt.Fprintf(&b, "export %s=%s\n", kv.Key, shell.Q(kv.Value))
		}
		return b.String()
	case ops.Note:
		return "# " + strings.ReplaceAll(t.Message, "\n", " ") + "\n"
	}
	return shell.Op(o, r.plan.Flavor)
}

// run adds a RUN instruction; secret values are replaced by BuildKit secrets.
func (r *renderer) run(script string, secret bool) error {
	var mounts []string
	if secret {
		var used []Secret
		var err error
		script, used, err = substituteSecrets(script, r.secrets)
		if err != nil {
			return err
		}
		for _, s := range used {
			r.used[s.ID] = true
			mounts = append(mounts, fmt.Sprintf("--mount=type=secret,id=%s,env=%s", s.ID, s.Env))
		}
	}
	r.emit(instr{script: script, mounts: mounts})
	return nil
}

// simpleLines reports whether each line is a complete simple command that can
// be joined with &&.
func simpleLines(lines []string) bool {
	if len(lines) > 4 {
		return false
	}
	for _, l := range lines {
		t := strings.TrimSpace(l)
		if t == "" || strings.HasPrefix(t, "#") || strings.ContainsAny(t, "<>|;&{}()`\\") ||
			strings.HasPrefix(t, "if ") || strings.HasPrefix(t, "for ") || strings.HasPrefix(t, "while ") ||
			strings.HasSuffix(t, " then") || strings.Count(t, "'")%2 != 0 || strings.Count(t, `"`)%2 != 0 {
			return false
		}
	}
	return true
}

// copy emits COPY with an inline heredoc.
func (r *renderer) copy(f ops.File) {
	mode := f.Mode
	if mode == "" {
		mode = "0644"
	}
	flags := "--chmod=" + mode
	if own := owner(f.Owner, f.Group); own != "" {
		flags += " --chown=" + own
	}
	c := string(f.Content)
	if c != "" && !strings.HasSuffix(c, "\n") {
		// A heredoc always ends with a newline; keep the exact content.
		r.run(shell.File(f), false)
		return
	}
	d := shell.Delimiter(c, "EOF")
	r.text("COPY %s <<'%s' %s\n%s%s", flags, d, quoteWord(f.Path), c, d)
}

func (r *renderer) addURL(d ops.Download) {
	flags := []string{}
	if d.SHA256 != "" {
		flags = append(flags, "--checksum=sha256:"+d.SHA256)
	}
	mode := d.Mode
	if mode == "" {
		mode = "0644"
	}
	flags = append(flags, "--chmod="+mode)
	if own := owner(d.Owner, d.Group); own != "" {
		flags = append(flags, "--chown="+own)
	}
	r.text("ADD %s %s %s", strings.Join(flags, " "), quoteWord(d.URL), quoteWord(d.Path))
}

func owner(o, g string) string {
	switch {
	case o != "" && g != "":
		return o + ":" + g
	case o != "":
		return o
	case g != "":
		return "root:" + g
	}
	return ""
}

// quote quotes a value for ENV/LABEL (double quotes, no variable expansion).
func quote(s string) string {
	s = strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, "\n", `\n`).Replace(s)
	return `"` + s + `"`
}

func quoteWord(s string) string {
	if strings.ContainsAny(s, " \t\"'$\\") {
		return quote(s)
	}
	return s
}

func list(v any) []string {
	switch t := v.(type) {
	case []any:
		var out []string
		for _, e := range t {
			out = append(out, expr.Stringify(e))
		}
		return out
	case string:
		if t == "" {
			return nil
		}
		return strings.Fields(t)
	case int64:
		return []string{strconv.FormatInt(t, 10)}
	}
	return nil
}

func jsonArray(l []string) string {
	b, _ := json.Marshal(l)
	return string(b)
}

func execForm(v any) string {
	if s, ok := v.(string); ok {
		return s
	}
	return jsonArray(list(v))
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
